export function genderizeChildText(text: string, gender: ChildGender | undefined, lang: Lang): string {
  if (gender !== 'female') return text;
  if (lang === 'en') {
    return text
      .replace(/\bhimself\b/gi, (word) => word[0] === word[0].toUpperCase() ? 'Herself' : 'herself')
      .replace(/\bhis\b/gi, (word) => word[0] === word[0].toUpperCase() ? 'Her' : 'her')
      .replace(/\bhim\b/gi, (word) => word[0] === word[0].toUpperCase() ? 'Her' : 'her')
      .replace(/\bhe\b/gi, (word) => word[0] === word[0].toUpperCase() ? 'She' : 'she');
  }
  return femaleArabicReplacements
    .reduce((result, [pattern, replacement]) => result.replace(pattern, replacement), text)
    .replace(/وتفهمها الغرباء/g, 'ويفهمها الغرباء')
    .replace(/هاا/g, 'ها');
}

/** For explanatory copy that may also contain masculine non-child subjects. */
export function genderizeChildReferences(text: string, gender: ChildGender | undefined, lang: Lang): string {
  if (gender !== 'female') return text;
  if (lang === 'en') return genderizeChildText(text, gender, lang);
  return femaleReferenceReplacements.reduce((result, [pattern, replacement]) => result.replace(pattern, replacement), text);
}

export function childGenderLabel(gender: ChildGender, lang: Lang): string {
  return lang === 'ar' ? (gender === 'female' ? 'أنثى' : 'ذكر') : (gender === 'female' ? 'Female' : 'Male');
}

export function childNoun(gender: ChildGender | undefined, lang: Lang): string {
  if (lang === 'en') return 'Child';
  return gender === 'female' ? 'الطفلة' : 'الطفل';
}
